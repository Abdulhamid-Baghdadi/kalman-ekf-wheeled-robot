Kalman Filter
clear all
sympref('AbbreviateOutput', false)
syms t_Delta ...
    x_new y_new theta_new ...
    x_old y_old theta_old ...
    A B ...
    v omega ...
    
A = [1 0 0; 0 1 0; 0 0 1]
B = [t_Delta 0 0; 0 t_Delta 0; 0 0 t_Delta]
u = [v*cos(theta_old); v*sin(theta_old); omega]
eq_1 = [x_new; y_new; theta_new] ==  A * [x_old ; y_old ; theta_old] + B * u

Extended Kalman Filter
clear all
sympref('AbbreviateOutput', false)
syms t_Delta ...
    x_new y_new theta_new ...
    x_old y_old theta_old ...
    A B ...
    v omega ...

x_new = x_old + t_Delta * v * cos(theta_old);
y_new = y_old + t_Delta * v * sin(theta_old);
theta_new = theta_old + t_Delta * omega;
[x_new; y_new; theta_new]
J_A = jacobian([x_new, y_new, theta_new], [x_old; y_old; theta_old])
J_B = jacobian([x_new, y_new, theta_new], [v; omega])
